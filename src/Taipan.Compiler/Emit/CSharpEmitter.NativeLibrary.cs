using System.Text;
using Taipan.Compiler.Semantics;

namespace Taipan.Compiler.Emit;

// A native library (SPEC §15.6, M45): the program class as usual, and a class of C entry points,
// each converting its C arguments, calling the function and converting its result, with what it
// raises kept as the thread's last error.
public sealed partial class CSharpEmitter
{
    private const string NativeExports = "global::Taipan.Runtime.NativeExports";

    private string NativeExportsClass(BoundNativeLibrary library)
    {
        var code = new StringBuilder();
        code.Append($"\npublic static unsafe class {UniqueGlobal("TaipanNativeExports")}\n{{\n");
        foreach (var function in library.Functions)
        {
            var parameters = string.Join(", ", function.Parameters.Select(p => $"{CType(p.Type, isResult: false)} @{p.Name}"));
            var arguments = string.Join(", ", function.Parameters.Select(p => FromC(p.Type, $"@{p.Name}")));
            var call = $"{_programPath}.@{_names[function]}({arguments})";
            var result = function.ReturnType is NothingType ? "void" : CType(function.ReturnType, isResult: true);
            code.Append($"    [global::System.Runtime.InteropServices.UnmanagedCallersOnly(EntryPoint = \"{library.Name}_{function.Name}\")]\n");
            code.Append($"    public static {result} @{function.Name}({parameters})\n    {{\n        try\n        {{\n");
            code.Append($"            {NativeExports}.Begin({_programPath}.{_topLevelMethod});\n");
            code.Append(function.ReturnType is NothingType ? $"            {call};\n" : $"            return {ToC(function.ReturnType, call)};\n");
            code.Append($"        }}\n        catch (global::System.Exception @e)\n        {{\n            {NativeExports}.Fail(@e);\n");
            if (function.ReturnType is not NothingType)
                code.Append("            return default;\n");
            code.Append("        }\n    }\n\n");
        }
        code.Append($"    [global::System.Runtime.InteropServices.UnmanagedCallersOnly(EntryPoint = \"{library.Name}_last_error\")]\n");
        code.Append($"    public static nint @__last_error() => {NativeExports}.LastError();\n\n");
        code.Append($"    [global::System.Runtime.InteropServices.UnmanagedCallersOnly(EntryPoint = \"{library.Name}_free\")]\n");
        code.Append($"    public static void @__free(nint @text) => {NativeExports}.Free(@text);\n");
        code.Append("}\n");
        return code.ToString();
    }

    // C's form of a Taipan type in an entry point's signature: a bool is a byte, and a str a pointer.
    private static string CType(TaipanType type, bool isResult) => type switch
    {
        PrimitiveType { Name: "int" } => "long",
        PrimitiveType { Name: "float" } => "double",
        PrimitiveType { Name: "bool" } => "byte",
        _ => "nint",
    };

    private static string FromC(TaipanType type, string value) => type switch
    {
        PrimitiveType { Name: "bool" } => $"({value} != 0)",
        PrimitiveType { Name: "str" } => $"{NativeExports}.Str({value})",
        _ => value,
    };

    private static string ToC(TaipanType type, string value) => type switch
    {
        PrimitiveType { Name: "bool" } => $"(byte)({value} ? 1 : 0)",
        PrimitiveType { Name: "str" } => $"{NativeExports}.FromStr({value})",
        _ => value,
    };

    /// <summary>The library's C header, declaring its exports (SPEC §15.6).</summary>
    private static string CHeader(BoundNativeLibrary library, string path)
    {
        var guard = $"{library.Name.ToUpperInvariant()}_H";
        var code = new StringBuilder();
        code.Append($"/* Generated by taipan from {path}. Do not edit. */\n");
        code.Append($"#ifndef {guard}\n#define {guard}\n\n#include <stdbool.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n\n");
        foreach (var function in library.Functions)
        {
            var parameters = function.Parameters.IsEmpty ? "void"
                : string.Join(", ", function.Parameters.Select(p => $"{CName(p.Type, isResult: false)}{CIdentifier(p.Name)}"));
            var result = function.ReturnType is NothingType ? "void " : CName(function.ReturnType, isResult: true);
            code.Append($"{result}{library.Name}_{function.Name}({parameters});\n");
        }
        code.Append($"\n/* The calling thread's last error, as \"<Class>: <message>\", or NULL after a call that returned normally. */\n");
        code.Append($"const char *{library.Name}_last_error(void);\n\n");
        code.Append($"/* Frees a string the library returned. */\n");
        code.Append($"void {library.Name}_free(char *text);\n\n");
        code.Append($"#ifdef __cplusplus\n}}\n#endif\n\n#endif\n");
        return code.ToString();
    }

    // A C type and the space before the name after it: `int64_t `, `const char *`.
    private static string CName(TaipanType type, bool isResult) => type switch
    {
        PrimitiveType { Name: "int" } => "int64_t ",
        PrimitiveType { Name: "float" } => "double ",
        PrimitiveType { Name: "bool" } => "bool ",
        _ => isResult ? "char *" : "const char *",
    };

    private static readonly HashSet<string> CKeywords =
    [
        "auto", "char", "const", "default", "do", "double", "enum", "extern", "float", "goto", "int", "long", "register",
        "restrict", "short", "signed", "sizeof", "static", "struct", "switch", "typedef", "union", "unsigned", "void", "volatile",
        "bool", "inline", "case",
    ];

    // A parameter's name in C, with `_` after one that's a C keyword.
    private static string CIdentifier(string name) => CKeywords.Contains(name) ? name + "_" : name;
}
