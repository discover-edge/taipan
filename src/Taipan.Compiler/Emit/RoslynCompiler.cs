using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Emit;
using Taipan.Runtime;

namespace Taipan.Compiler.Emit;

/// <summary>Compiles emitted C# in-process with Roslyn (SPEC §8) and runs or saves the result.</summary>
public static class RoslynCompiler
{
    private static readonly Lazy<ImmutableArray<MetadataReference>> References = new(LoadReferences);

    /// <summary>
    /// Compiles to an assembly image with an embedded PDB, so panics can map stack frames back
    /// to <c>.tpn</c> lines. The emitted C# is generated by us, so a C# error is a compiler bug.
    /// </summary>
    /// <remarks>
    /// Without <paramref name="debugInformation"/>, stack traces have no lines, as in a native build,
    /// so panics report only what the program recorded (SPEC §15.3); tests use that to check it.
    /// </remarks>
    public static byte[] Compile(EmittedProgram program, string assemblyName, bool debugInformation = true, string? version = null)
    {
        var csharp = program.Code;
        var tree = CSharpSyntaxTree.ParseText(
            csharp,
            new CSharpParseOptions(LanguageVersion.Latest),
            path: assemblyName + ".g.cs",
            encoding: Encoding.UTF8);
        SyntaxTree[] trees = version is null ? [tree] : [tree, VersionTree(version)];

        // A library has no entry point (SPEC §14.4).
        var options = new CSharpCompilationOptions(
            program.EntryClass is null ? OutputKind.DynamicallyLinkedLibrary : OutputKind.ConsoleApplication,
            mainTypeName: program.EntryClass,
            optimizationLevel: OptimizationLevel.Debug,
            checkOverflow: true,
            nullableContextOptions: NullableContextOptions.Enable);

        var compilation = CSharpCompilation.Create(assemblyName, trees, ReferencesFor(program), options);
        using var image = new MemoryStream();
        var result = debugInformation
            ? compilation.Emit(image, options: new EmitOptions(debugInformationFormat: DebugInformationFormat.Embedded))
            : compilation.Emit(image);
        if (!result.Success)
        {
            var errors = result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error);
            throw new InvalidOperationException(
                "generated C# failed to compile:\n" + string.Join("\n", errors) + "\n\n" + csharp);
        }
        return image.ToArray();
    }

    /// <summary>
    /// Runs a compiled program in a collectible load context, with its output redirected and the
    /// assemblies it references (SPEC §13.2) loaded from their paths. Returns its exit code: 0,
    /// or 101 after a panic.
    /// </summary>
    public static int Run(byte[] image, ImmutableArray<string> assemblies, TextWriter stdout, TextWriter stderr)
    {
        var context = new AssemblyLoadContext("taipan-program", isCollectible: true);
        var byName = assemblies.ToLookup(path => Path.GetFileNameWithoutExtension(path), StringComparer.OrdinalIgnoreCase);
        context.Resolving += (loader, name) =>
            byName[name.Name ?? ""].FirstOrDefault() is { } path ? loader.LoadFromAssemblyPath(path) : null;
        var (savedOut, savedError) = (Io.Out, Io.Error);
        try
        {
            Io.Out = stdout;
            Io.Error = stderr;
            var assembly = context.LoadFromStream(new MemoryStream(image));
            var entryPoint = assembly.EntryPoint ?? throw new InvalidOperationException("compiled program has no entry point");
            return (int)entryPoint.Invoke(null, null)!;
        }
        catch (TargetInvocationException e) when (e.InnerException is not null)
        {
            System.Runtime.ExceptionServices.ExceptionDispatchInfo.Throw(e.InnerException);
            throw;
        }
        finally
        {
            (Io.Out, Io.Error) = (savedOut, savedError);
            context.Unload();
        }
    }

    /// <summary>
    /// Writes a runnable program to <paramref name="directory"/>: the assembly, the runtime and
    /// other assemblies it references, and a runtimeconfig so <c>dotnet &lt;name&gt;.dll</c> runs it.
    /// A library gets no runtimeconfig, since it doesn't run by itself (SPEC §14.4).
    /// </summary>
    public static string Save(byte[] image, string assemblyName, string directory, ImmutableArray<string> assemblies, bool library = false)
    {
        Directory.CreateDirectory(directory);
        var path = Path.Combine(directory, assemblyName + ".dll");
        File.WriteAllBytes(path, image);

        foreach (var dependency in (string[])[typeof(Panic).Assembly.Location, Interop.PythonRuntimeAssembly, .. assemblies])
            File.Copy(dependency, Path.Combine(directory, Path.GetFileName(dependency)), overwrite: true);
        if (library)
            return path;

        var version = Environment.Version;
        File.WriteAllText(Path.Combine(directory, assemblyName + ".runtimeconfig.json"), $$"""
            {
              "runtimeOptions": {
                "tfm": "net{{version.Major}}.{{version.Minor}}",
                "framework": { "name": "Microsoft.NETCore.App", "version": "{{version.Major}}.{{version.Minor}}.0" }
              }
            }
            """);
        return path;
    }

    /// <summary>
    /// A library's version (SPEC §18.3): its numeric part as the assembly's version, and the whole as
    /// its informational version, since a prerelease isn't an assembly version.
    /// </summary>
    private static SyntaxTree VersionTree(string version)
    {
        var numeric = version.Split('-', '+')[0];
        var parts = numeric.Split('.');
        var assemblyVersion = string.Join(".", parts.Concat(Enumerable.Repeat("0", 4 - parts.Length)));
        return CSharpSyntaxTree.ParseText(
            $"[assembly: global::System.Reflection.AssemblyVersion(\"{assemblyVersion}\")]\n"
            + $"[assembly: global::System.Reflection.AssemblyFileVersion(\"{assemblyVersion}\")]\n"
            + $"[assembly: global::System.Reflection.AssemblyInformationalVersion(\"{version}\")]\n",
            new CSharpParseOptions(LanguageVersion.Latest), path: "version.g.cs", encoding: Encoding.UTF8);
    }

    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, MetadataReference> ByPath = new();

    /// <summary>
    /// A program using .NET compiles against every assembly it may use (SPEC §13.2), which include
    /// the defaults' framework assemblies; any other against the defaults.
    /// </summary>
    private static ImmutableArray<MetadataReference> ReferencesFor(EmittedProgram program)
    {
        if (program.References.IsEmpty)
            return References.Value;
        // An SDK project's references bring the runtime from its package already (SPEC §18.1).
        var given = program.References.Select(Path.GetFileName).ToHashSet(StringComparer.OrdinalIgnoreCase);
        return
        [
            .. program.References.Select(path => ByPath.GetOrAdd(path, p => MetadataReference.CreateFromFile(p))),
            .. ((string[])[typeof(Panic).Assembly.Location, Interop.PythonRuntimeAssembly])
                .Where(path => !given.Contains(Path.GetFileName(path))).Select(path => MetadataReference.CreateFromFile(path)),
        ];
    }

    // Compiles against the running framework's assemblies plus Taipan.Runtime.
    private static ImmutableArray<MetadataReference> LoadReferences()
    {
        var frameworkDirectory = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        // netstandard for Python.Runtime, which targets .NET Standard, and System.Linq.Expressions
        // because its PyObject derives from DynamicObject (SPEC §10).
        string[] framework =
        [
            "System.Private.CoreLib.dll", "System.Runtime.dll", "System.Collections.dll",
            "netstandard.dll", "System.Linq.Expressions.dll",
        ];
        return
        [
            .. framework.Select(name => MetadataReference.CreateFromFile(Path.Combine(frameworkDirectory, name))),
            MetadataReference.CreateFromFile(typeof(Panic).Assembly.Location),
            MetadataReference.CreateFromFile(Interop.PythonRuntimeAssembly),
        ];
    }
}
