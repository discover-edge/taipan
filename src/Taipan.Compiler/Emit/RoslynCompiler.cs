using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Emit;
using Taipan.Runtime;

namespace Taipan.Compiler.Emit;

/// <summary>Compiles emitted C# in-process with Roslyn (SPEC §8) and runs or saves the result.</summary>
public static class RoslynCompiler
{
    private static readonly Lazy<ImmutableArray<MetadataReference>> References = new(LoadReferences);

    /// <summary>
    /// Compiles to an assembly image with an embedded PDB, so panics can map stack frames back
    /// to <c>.tpn</c> lines. The emitted C# is generated by us, so a C# error is a compiler bug.
    /// </summary>
    public static byte[] Compile(EmittedProgram program, string assemblyName)
    {
        var csharp = program.Code;
        var tree = CSharpSyntaxTree.ParseText(
            csharp,
            new CSharpParseOptions(LanguageVersion.Latest),
            path: assemblyName + ".g.cs",
            encoding: Encoding.UTF8);

        var options = new CSharpCompilationOptions(
            OutputKind.ConsoleApplication,
            mainTypeName: program.EntryClass,
            optimizationLevel: OptimizationLevel.Debug,
            checkOverflow: true,
            nullableContextOptions: NullableContextOptions.Enable);

        var compilation = CSharpCompilation.Create(assemblyName, [tree], References.Value, options);
        using var image = new MemoryStream();
        var result = compilation.Emit(image, options: new EmitOptions(debugInformationFormat: DebugInformationFormat.Embedded));
        if (!result.Success)
        {
            var errors = result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error);
            throw new InvalidOperationException(
                "generated C# failed to compile:\n" + string.Join("\n", errors) + "\n\n" + csharp);
        }
        return image.ToArray();
    }

    /// <summary>
    /// Runs a compiled program in a collectible load context, with its output redirected.
    /// Returns its exit code: 0, or 101 after a panic.
    /// </summary>
    public static int Run(byte[] image, TextWriter stdout, TextWriter stderr)
    {
        var context = new AssemblyLoadContext("taipan-program", isCollectible: true);
        var (savedOut, savedError) = (Io.Out, Io.Error);
        try
        {
            Io.Out = stdout;
            Io.Error = stderr;
            var assembly = context.LoadFromStream(new MemoryStream(image));
            var entryPoint = assembly.EntryPoint ?? throw new InvalidOperationException("compiled program has no entry point");
            return (int)entryPoint.Invoke(null, null)!;
        }
        catch (TargetInvocationException e) when (e.InnerException is not null)
        {
            System.Runtime.ExceptionServices.ExceptionDispatchInfo.Throw(e.InnerException);
            throw;
        }
        finally
        {
            (Io.Out, Io.Error) = (savedOut, savedError);
            context.Unload();
        }
    }

    /// <summary>
    /// Writes a runnable program to <paramref name="directory"/>: the assembly, the runtime it
    /// references, and a runtimeconfig so <c>dotnet &lt;name&gt;.dll</c> runs it.
    /// </summary>
    public static string Save(byte[] image, string assemblyName, string directory)
    {
        Directory.CreateDirectory(directory);
        var path = Path.Combine(directory, assemblyName + ".dll");
        File.WriteAllBytes(path, image);

        var runtime = typeof(Panic).Assembly.Location;
        File.Copy(runtime, Path.Combine(directory, Path.GetFileName(runtime)), overwrite: true);

        var version = Environment.Version;
        File.WriteAllText(Path.Combine(directory, assemblyName + ".runtimeconfig.json"), $$"""
            {
              "runtimeOptions": {
                "tfm": "net{{version.Major}}.{{version.Minor}}",
                "framework": { "name": "Microsoft.NETCore.App", "version": "{{version.Major}}.{{version.Minor}}.0" }
              }
            }
            """);
        return path;
    }

    // Compiles against the running framework's assemblies plus Taipan.Runtime.
    private static ImmutableArray<MetadataReference> LoadReferences()
    {
        var frameworkDirectory = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        string[] framework = ["System.Private.CoreLib.dll", "System.Runtime.dll", "System.Collections.dll"];
        return
        [
            .. framework.Select(name => MetadataReference.CreateFromFile(Path.Combine(frameworkDirectory, name))),
            MetadataReference.CreateFromFile(typeof(Panic).Assembly.Location),
        ];
    }
}
